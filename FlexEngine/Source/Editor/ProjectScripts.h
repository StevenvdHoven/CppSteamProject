#pragma once
#include <filesystem>
#include <string>
#include <vector>

namespace Flex
{
	class OutputLog;
	class Project;

	// A project's C++ game code ("scripts"): <Project>/Source/, built into <Name>.dll.
	//  - The editor generates Source/<Name>.vcxproj and <Name>.sln (no absolute paths, safe to
	//    commit). The engine's location comes from Saved/FlexEngine.props, which the editor
	//    rewrites on every start (per machine, gitignored).
	//  - The project compiles every .cpp/.h under Source/ (wildcards), so new scripts need no
	//    project file changes.
	//  - A .vcxproj without the "Generated by FlexEditor" marker (e.g. the SpriteStorm sample,
	//    which is part of the engine solution) is used as it is and never rewritten.
	namespace ProjectScripts
	{
		enum class ScriptTemplate
		{
			Component,          // a data component with Serialize, registered
			System,             // an Update system function, registered
			ComponentAndSystem  // both: the component plus a system that processes it
		};

		std::filesystem::path GetSourceDirectory(const Project& project);
		std::filesystem::path GetModuleProjectFile(const Project& project);
		std::filesystem::path GetSolutionFile(const Project& project);

		// Rewrites Saved/FlexEngine.props when the project has a generated module project.
		void UpdateEngineLocation(const Project& project);

		// Creates Source/, Saved/FlexEngine.props and (when missing) the .vcxproj and .sln.
		bool EnsureProjectFiles(const Project& project, std::string& outError);

		// Letters, digits and '_', starting with a letter; not taken; not the project's name.
		bool IsValidScriptName(const Project& project, const std::string& name, std::string& outError);

		// Writes the new files (Source/<Name>.h and/or .cpp) and returns them.
		bool CreateScript(const Project& project, const std::string& name, ScriptTemplate scriptTemplate,
			std::vector<std::filesystem::path>& outFiles, std::string& outError);

		// Every .h/.cpp under Source/, relative to it, sorted.
		std::vector<std::filesystem::path> ListScripts(const Project& project);

		// Builds the module with MSBuild in the given configuration (blocking: run it on a
		// background thread). Output lines go to log.
		bool BuildModule(const Project& project, const std::string& configuration, OutputLog& log);
	}
}

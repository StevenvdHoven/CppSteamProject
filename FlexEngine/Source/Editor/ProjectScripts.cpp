		const char* ComponentHeaderTemplate = R"FLEX(#pragma once
#include "Core/Serialization/Archive.h"
#include "Core/World/ComponentRegistery.h"
#include <cstdint>

namespace $PROJECT$
{
	// A data component. Its fields show up in the Inspector and are saved in scenes
	// through Serialize. Add it to a GameObject with Add Component.
	struct $NAME$
	{
		FLEX_COMPONENT($NAME$)
		static constexpr uint32_t Version = 1;

		float Speed = 100.0f;

		void Serialize(Flex::Archive& archive)
		{
			archive.SerializeVersion(Version);
			archive.Field("Speed", Speed);
		}
	};
}
)FLEX";

		const char* ComponentSourceTemplate = R"FLEX(#include "$NAME$.h"

namespace $PROJECT$
{
	FLEX_REGISTER_COMPONENT($NAME$)
}
)FLEX";


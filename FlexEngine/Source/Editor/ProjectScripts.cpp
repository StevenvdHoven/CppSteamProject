		constexpr const char* GeneratedMarker = "Generated by FlexEditor";

		bool WriteTextFile(const std::filesystem::path& file, const std::string& text, std::string& outError)
		{
			std::ofstream stream(file, std::ios::binary | std::ios::trunc);
			if (!stream.is_open()) {
				outError = "Could not write " + PathToUtf8(file);
				return false;
			}
			stream << text;
			return stream.good();
		}

		std::string ReadTextFile(const std::filesystem::path& file)
		{
			std::ifstream stream(file, std::ios::binary);
			std::stringstream text;
			text << stream.rdbuf();
			return text.str();
		}

		// "{8-4-4-4-12}" from two random ids.
		std::string MakeGuid()
		{
			const std::string a = Uid::Generate().ToString();
			const std::string b = Uid::Generate().ToString();
			std::string guid = "{" + a.substr(0, 8) + "-" + a.substr(8, 4) + "-" + a.substr(12, 4) + "-" + b.substr(0, 4) + "-" + b.substr(4, 12) + "}";
			std::transform(guid.begin(), guid.end(), guid.begin(), [](unsigned char c) { return static_cast<char>(std::toupper(c)); });
			return guid;
		}

		std::string ReplaceAll(std::string text, const std::string& from, const std::string& to)
		{
			for (size_t at = text.find(from); at != std::string::npos; at = text.find(from, at + to.size())) {
				text.replace(at, from.size(), to);
			}
			return text;
		}

